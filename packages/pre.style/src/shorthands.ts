// Each CSS shorthand and the most specific longhands it sets. The compiler
// uses it to set longhands a shorthand resets to `initial`, and `cn` uses
// it for shorthands that weren't expanded (`margin: var(--m)`,
// `font: inherit`).

const sides = (prefix: string, suffix = '') =>
  ['top', 'right', 'bottom', 'left'].map((side) => `${prefix}${side}${suffix}`);
const logical = (prefix: string, axis: 'block' | 'inline', suffix = '') => [
  `${prefix}-${axis}-start${suffix}`,
  `${prefix}-${axis}-end${suffix}`,
];
const borderSide = (side: string) => [
  `border-${side}-width`,
  `border-${side}-style`,
  `border-${side}-color`,
];

